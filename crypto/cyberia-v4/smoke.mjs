import { network } from 'hardhat';
import { AbiCoder, BrowserProvider, ContractFactory, MaxUint256, Wallet, ZeroAddress, ZeroHash, parseEther } from 'ethers';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { permit2Artifact, wrappedCyberArtifact } from './compile.mjs';
import { executeV4, quoteV4 } from '../../backend/laravel/resources/js/lib/wallet/v4.ts';
const require = createRequire(import.meta.url);
const { provider: rpc } = await network.create({ network: 'simulated' });
const provider = new BrowserProvider(rpc, undefined, { cacheTimeout: -1 });
provider.pollingInterval = 50;
const signer = await provider.getSigner();
const artifact = (name) => require(`@uniswap/v4-core/out/${name}.sol/${name}.json`);
const deploy = async (name, ...args) => {
  const a = artifact(name);
  const c = await new ContractFactory(a.abi, a.bytecode.object, signer).deploy(...args);
  await c.waitForDeployment();
  return c;
};
const manager = await deploy('PoolManager', await signer.getAddress());
const permitArtifact = permit2Artifact();
const permit = await new ContractFactory(permitArtifact.abi, permitArtifact.bytecode, signer).deploy();
await permit.waitForDeployment();
const wethArtifact = wrappedCyberArtifact();
const weth = await new ContractFactory(wethArtifact.abi, wethArtifact.bytecode, signer).deploy();
await weth.waitForDeployment();
const descriptorArtifact = require('@uniswap/v4-periphery/foundry-out/PositionDescriptor.sol/PositionDescriptor.json');
const descriptor = await new ContractFactory(descriptorArtifact.abi, descriptorArtifact.bytecode.object, signer).deploy(await manager.getAddress(), await weth.getAddress(), '0x4359424552000000000000000000000000000000000000000000000000000000');
await descriptor.waitForDeployment();
const positionArtifact = require('@uniswap/v4-periphery/foundry-out/PositionManager.sol/PositionManager.json');
const positions = await new ContractFactory(positionArtifact.abi, positionArtifact.bytecode.object, signer).deploy(await manager.getAddress(), await permit.getAddress(), 300000, await descriptor.getAddress(), await weth.getAddress());
await positions.waitForDeployment();
const liquidity = await deploy('PoolModifyLiquidityTest', await manager.getAddress());
const swapper = await deploy('PoolSwapTest', await manager.getAddress());
const mock = require('@uniswap/v4-core/out/mocks/MockERC20.sol/MockERC20.json');
const token = await new ContractFactory(mock.abi, mock.bytecode.object, signer).deploy('Test Token', 'TEST', 18);
await token.waitForDeployment();
await (await token.mint(await signer.getAddress(), parseEther('100000'))).wait();
await (await token.approve(await liquidity.getAddress(), MaxUint256)).wait();
// 20,000 pips = 2% LP fee. This is a pool setting in the local test.
const key = [ZeroAddress, await token.getAddress(), 20_000, 60, ZeroAddress];
await (await manager.initialize(key, 2n ** 96n)).wait();
const coder = AbiCoder.defaultAbiCoder();
const poolType = 'tuple(address currency0,address currency1,uint24 fee,int24 tickSpacing,address hooks)';
await (await token.approve(await permit.getAddress(), MaxUint256)).wait();
await (await permit.approve(await token.getAddress(), await positions.getAddress(), (1n << 160n) - 1n, (1n << 48n) - 1n)).wait();
const mint = coder.encode([poolType,'int24','int24','uint256','uint128','uint128','address','bytes'], [key, -600, 600, parseEther('1000'), parseEther('50'), parseEther('50'), await signer.getAddress(), '0x']);
const pair = coder.encode(['address','address'], [ZeroAddress, await token.getAddress()]);
const mintPlan = coder.encode(['bytes','bytes[]'], ['0x020d', [mint, pair]]);
await (await positions.modifyLiquidities(mintPlan, Math.floor(Date.now()/1000)+600, {value: parseEther('50')})).wait();
if (await positions.balanceOf(await signer.getAddress()) !== 1n) throw new Error('Position NFT not minted');
console.log('Official Permit2 and PositionManager minted a liquidity position');
await (await liquidity['modifyLiquidity((address,address,uint24,int24,address),(int24,int24,int256,bytes32),bytes)'](key, [-600, 600, parseEther('1000'), ZeroHash], '0x', { value: parseEther('50') })).wait();
const q = require('@uniswap/v4-periphery/foundry-out/V4Quoter.sol/V4Quoter.json');
const quoter = await new ContractFactory(q.abi, q.bytecode.object, signer).deploy(await manager.getAddress());
await quoter.waitForDeployment();
const feeQuote = await quoter.quoteExactInputSingle.staticCall([key, true, parseEther('1'), '0x']);
// At a 1:1 spot price, output must be below 0.98 after the 2% fee;
// the small additional difference is price impact in the test pool.
if (feeQuote[0] >= parseEther('0.98') || feeQuote[0] <= parseEther('0.979')) throw new Error('Unexpected quote for 2% pool fee');
console.log('2% pool fee checked against the initial 1:1 quote');
const before = await token.balanceOf(await signer.getAddress());
await (await swapper.swap(key, [true, -parseEther('1'), 4295128740n], [false, false], '0x', { value: parseEther('1') })).wait();
const received = (await token.balanceOf(await signer.getAddress())) - before;
if (received <= 0n) throw new Error('Swap produced no tokens');
console.log('Initialized native/token v4 pool, added liquidity and swapped 1 native for', received.toString(), 'token units');
const quote = await quoter.quoteExactInputSingle.staticCall([key, true, parseEther('1'), '0x']);
const a = require('@uniswap/universal-router/artifacts/contracts/UniversalRouter.sol/UniversalRouter.json');
const router = await new ContractFactory(a.abi, a.bytecode, signer).deploy([await permit.getAddress(), await weth.getAddress(), ZeroAddress, ZeroAddress, ZeroHash, ZeroHash, await manager.getAddress(), ZeroAddress, await positions.getAddress(), ZeroAddress]);
await router.waitForDeployment();
const swap = coder.encode([`tuple(${poolType} poolKey,bool zeroForOne,uint128 amountIn,uint128 amountOutMinimum,bytes hookData)`], [[key, true, parseEther('1'), quote[0] * 99n / 100n, '0x']]);
const settle = coder.encode(['address','uint256'], [ZeroAddress, parseEther('1')]);
const take = coder.encode(['address','uint256'], [await token.getAddress(), quote[0] * 99n / 100n]);
const input = coder.encode(['bytes','bytes[]'], ['0x060c0f', [swap, settle, take]]);
const beforeRouter = await token.balanceOf(await signer.getAddress());
await (await router['execute(bytes,bytes[],uint256)']('0x10', [input], Math.floor(Date.now()/1000)+600, { value: parseEther('1') })).wait();
const routed = (await token.balanceOf(await signer.getAddress())) - beforeRouter;
if (routed < quote[0] * 99n / 100n) throw new Error('Router did not respect minimum output');
console.log('Official quoter and Universal Router delivered', routed.toString(), 'token units, floor enforced');
await (await permit.approve(await token.getAddress(), await router.getAddress(), (1n << 160n) - 1n, (1n << 48n) - 1n)).wait();
const reverseQuote = await quoter.quoteExactInputSingle.staticCall([key, false, parseEther('1'), '0x']);
const reverseSwap = coder.encode([`tuple(${poolType} poolKey,bool zeroForOne,uint128 amountIn,uint128 amountOutMinimum,bytes hookData)`], [[key, false, parseEther('1'), reverseQuote[0] * 99n / 100n, '0x']]);
const reverseSettle = coder.encode(['address','uint256'], [await token.getAddress(), parseEther('1')]);
const reverseTake = coder.encode(['address','uint256'], [ZeroAddress, reverseQuote[0] * 99n / 100n]);
const reverseInput = coder.encode(['bytes','bytes[]'], ['0x060c0f', [reverseSwap, reverseSettle, reverseTake]]);
const oldTokenBalance = await token.balanceOf(await signer.getAddress());
await (await router['execute(bytes,bytes[],uint256)']('0x10', [reverseInput], Math.floor(Date.now()/1000)+600)).wait();
if (oldTokenBalance - await token.balanceOf(await signer.getAddress()) !== parseEther('1')) throw new Error('Unexpected token payment');
console.log('Reverse token-to-native swap succeeded through Permit2');
const buyer = Wallet.createRandom().connect(provider);
await (await signer.sendTransaction({ to: buyer.address, value: parseEther('20') })).wait();
await (await token.mint(buyer.address, parseEther('10'))).wait();
const stateArtifact = require('@uniswap/v4-periphery/foundry-out/StateView.sol/StateView.json');
const stateView = await new ContractFactory(stateArtifact.abi, stateArtifact.bytecode.object, signer).deploy(await manager.getAddress());
await stateView.waitForDeployment();
const config = { chainId: Number((await provider.getNetwork()).chainId), manager: await manager.getAddress(), router: await router.getAddress(), permit2: await permit.getAddress(), quoter: await quoter.getAddress(), stateView: await stateView.getAddress(), token: await token.getAddress(), fee: 20_000, tickSpacing: 60 };
const source = { kind: 'key', secret: buyer.privateKey };
const buyQuote = await quoteV4(provider, config, buyer.address, true, parseEther('1'));
assert.equal(buyQuote.minOut, buyQuote.amountOut * 99n / 100n);
await assert.rejects(executeV4(source, provider, { ...buyQuote, deadline: 0 }, config), /expired/);
await assert.rejects(executeV4(source, provider, buyQuote, { ...config, router: ZeroAddress }), /configuration changed/);
const buyerBefore = await token.balanceOf(buyer.address);
const buyHash = await executeV4(source, provider, buyQuote, config);
assert.equal((await provider.waitForTransaction(buyHash)).status, 1);
assert.ok((await token.balanceOf(buyer.address)) - buyerBefore >= buyQuote.minOut);
const sellQuote = await quoteV4(provider, config, buyer.address, false, parseEther('1'));
assert.ok(sellQuote.tokenApproval && sellQuote.permitApproval);
const sellHash = await executeV4(source, provider, sellQuote, config);
assert.equal((await provider.waitForTransaction(sellHash)).status, 1);
console.log('Wallet quote and signing succeeded in both directions with exact approvals and minimum output');
for (const [name, contract] of [['PoolManager', manager], ['Permit2', permit], ['wrapped native', weth], ['PositionDescriptor', descriptor], ['PositionManager', positions], ['V4Quoter', quoter], ['UniversalRouter', router]]) {
    const receipt = await contract.deploymentTransaction().wait();
    console.log(name, 'deployment gas', receipt.gasUsed.toString());
}
