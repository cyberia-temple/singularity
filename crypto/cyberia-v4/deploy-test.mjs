import assert from 'node:assert/strict';
import { mkdtemp, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { network } from 'hardhat';
import { BrowserProvider, Wallet, parseEther } from 'ethers';
import { deployStack } from './deploy.mjs';

const connection = await network.create({ network: 'simulated' });
const provider = new BrowserProvider(connection.provider, undefined, { cacheTimeout: -1 });
provider.pollingInterval = 50;
const funder = await provider.getSigner();
const signer = Wallet.createRandom().connect(provider);
await (await funder.sendTransaction({ to: signer.address, value: parseEther('8000') })).wait();
const checkpoint = join(await mkdtemp(join(tmpdir(), 'cyber-v4-')), 'deployment.json');
const options = { provider, signer, owner: await funder.getAddress(), path: checkpoint, expectedChainId: (await provider.getNetwork()).chainId, maxGasPrice: parseEther('0.0001') };
let paused = false;
await assert.rejects(deployStack({ ...options, onSaved: () => { if (!paused) { paused = true; throw new Error('simulated crash'); } } }), /simulated crash/);
const pending = JSON.parse(await readFile(checkpoint, 'utf8'));
assert.equal(pending.steps[0].status, 'signed');
const hash = pending.steps[0].hash;
const completed = await deployStack(options);
assert.ok(completed.steps.every((step) => step.status === 'confirmed'));
assert.equal(completed.steps[0].hash, hash);
assert.ok(completed.steps.every((step) => !step.raw));
const again = await deployStack(options);
assert.deepEqual(again.steps.map((step) => step.hash), completed.steps.map((step) => step.hash));
await assert.rejects(deployStack({ ...options, expectedChainId: 49407 }), /Unexpected chain/);
console.log('Deploy checkpoint resumes the same signed transaction and is idempotent');
